"""Inspect the local rsl-rl tree. GPU LocoLab fields stay empty until filled."""

from __future__ import annotations

import ast
import subprocess
from pathlib import Path


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[3]


def _version(pyproject: Path) -> str | None:
    if not pyproject.is_file():
        return None
    for line in pyproject.read_text().splitlines():
        if line.startswith("version = "):
            return line.split("=", 1)[1].strip().strip('"')
    return None


def _classes(directory: Path) -> list[str]:
    found: list[str] = []
    if not directory.is_dir():
        return found
    for path in sorted(directory.glob("*.py")):
        tree = ast.parse(path.read_text())
        found.extend(
            node.name
            for node in tree.body
            if isinstance(node, ast.ClassDef)
        )
    return found


def _git_commit(path: Path) -> str | None:
    if not (path / ".git").exists():
        return None
    try:
        out = subprocess.check_output(
            ["git", "-C", str(path), "rev-parse", "--short", "HEAD"],
            text=True,
            stderr=subprocess.DEVNULL,
        )
    except (subprocess.CalledProcessError, FileNotFoundError):
        return None
    return out.strip() or None


def _has_conv(directory: Path) -> bool:
    if not directory.is_dir():
        return False
    for path in directory.rglob("*.py"):
        text = path.read_text(errors="ignore")
        if "Conv2d" in text or "nn.Conv" in text:
            return True
    return False


def audit_local(*, root: Path | None = None) -> dict:
    root = root or _repo_root()
    rsl = root / "official" / "rsl_rl"
    modules = rsl / "rsl_rl" / "modules"
    classes = _classes(modules)
    isaac = root / "official" / "IsaacLab"
    return {
        "audited_on": "mac_local_clone",
        "gpu_host_audited": False,
        "isaac_lab_local_clone": isaac.is_dir(),
        "isaac_lab_version": None,
        "locolab_path": None,
        "locolab_task_id": None,
        "checkpoint_path": None,
        "checkpoint_actor_obs": None,
        "checkpoint_critic_obs": None,
        "checkpoint_actions": None,
        "rsl_rl_path": str(rsl),
        "rsl_rl_version": _version(rsl / "pyproject.toml"),
        "rsl_rl_commit": _git_commit(rsl),
        "policy_classes": classes,
        "has_cnn_encoder": _has_conv(rsl / "rsl_rl"),
        "actor_observation": "flat tensor from VecEnv.get_observations(); shape (N, num_obs)",
        "critic_observation": 'optional extras["observations"]["critic"]',
        "observation_groups": "actor tensor plus optional critic/teacher/rnd_state; no image group",
        "ppo_file": "rsl_rl/algorithms/ppo.py",
        "edit_ppo": False,
        "perception_placement": "ObservationTerm emits the 4-D semantic vector; actor stays an MLP",
        "camera_support_in_rsl_rl": False,
    }


def to_yaml(data: dict) -> str:
    lines = ["# Generated by semantic_locomotion.stack_audit. Do not hand-edit GPU fields."]
    for key, value in data.items():
        if isinstance(value, bool):
            rendered = "true" if value else "false"
        elif value is None:
            rendered = "null"
        elif isinstance(value, list):
            rendered = "[" + ", ".join(value) + "]"
        else:
            text = str(value).replace('"', '\\"')
            rendered = f'"{text}"'
        lines.append(f"{key}: {rendered}")
    lines.append("")
    return "\n".join(lines)
